    /**
     * Windows into the vacuum tube, so the plasma can be seen from the middle of the ring: on the inside of each side
     * of
     * the racetrack, the casing and the outer coil behind it are fusion glass for a few blocks. Each is
     * {sliceFrom, sliceTo, colFrom, colTo}, over the rows of the tube. Only fusion casing and outer coil are replaced,
     * so a window costs a few coils; make them smaller to keep more.
     */
    private static final int WINDOW_ROW_FROM = 13, WINDOW_ROW_TO = 15;
    private static final int[][] WINDOWS = {
            { 26, 30, 9, 10 }, // the left side
            { 26, 30, 41, 42 }, // the right side
            { 12, 13, 23, 27 }, // the far side
            { 44, 45, 23, 27 } // the near side
    };

    private static void windows(String[][] out) {
        for (int[] w : WINDOWS) {
            for (int s = w[0]; s <= w[1]; s++) {
                for (int r = WINDOW_ROW_FROM; r <= WINDOW_ROW_TO; r++) {
                    char[] c = out[s][r].toCharArray();
                    for (int col = w[2]; col <= w[3]; col++) {
                        if (c[col] == 'i' || c[col] == 'j') c[col] = 'w';
                    }
                    out[s][r] = new String(c);
                }
            }
        }
    }

    private static TraceabilityPredicate block(char key) {
        String id = BLOCKS.get(key);
        ResourceLocation rl = id == null ? null : ResourceLocation.tryParse(id);
        Block block = rl == null ? null : ForgeRegistries.BLOCKS.getValue(rl);
        if (block == null || block == net.minecraft.world.level.block.Blocks.AIR) {
            if (id != null) {
                PhoenixFission.LOGGER.warn("Fusion structure: block '{}' not found, '{}' matches anything", id, key);
            }
            return Predicates.any();
        }
        return Predicates.blocks(block);
    }

    public static BlockPattern build(MultiblockMachineDefinition definition) {
        var builder = FactoryBlockPattern.start(RelativeDirection.FRONT, RelativeDirection.UP,
                RelativeDirection.RIGHT);
        String[][] slices = new String[SLICES.length][];
        for (int i = 0; i < SLICES.length; i++) slices[i] = SLICES[i].clone();
        windows(slices);
        for (String[] slice : slices) builder = builder.aisle(slice);

        for (char key : BLOCKS.keySet()) {
            if ("jlzynBxogq".indexOf(key) >= 0) continue;
            builder = builder.where(key, block(key));
        }

        TraceabilityPredicate hatchCasing = Predicates.blocks(PhoenixFissionBlocks.FISSILE_REACTION_SAFE_CASING.get())
                .or(Predicates.abilities(PartAbility.INPUT_ENERGY))
                .or(Predicates.abilities(PartAbility.OUTPUT_ENERGY))
                .or(Predicates.abilities(PartAbility.IMPORT_FLUIDS))
                .or(Predicates.abilities(PartAbility.EXPORT_FLUIDS))
                .or(Predicates.abilities(PartAbility.IMPORT_ITEMS))
                .or(Predicates.abilities(PartAbility.EXPORT_ITEMS))
                .or(Predicates.abilities(PartAbility.MAINTENANCE).setExactLimit(1))
                .or(Predicates.abilities(PhoenixPartAbility.FISSION_SCRAM).setMaxGlobalLimited(1))
                .or(Predicates.abilities(PhoenixPartAbility.FISSION_SENSOR).setMaxGlobalLimited(2));

        TraceabilityPredicate energySlot = Predicates.abilities(PartAbility.INPUT_ENERGY)
                .or(Predicates.abilities(PartAbility.OUTPUT_ENERGY));

        builder = builder
                .where('B', hatchCasing)
                .where('n', energySlot)
                .where('j', PhoenixFissionPredicates.fusionOuterCoils())
                .where('l', PhoenixFissionPredicates.fusionInnerCoils())
                .where('z', Predicates.any())
                .where('y', Predicates.controller(Predicates.blocks(definition.get())))
                .where(' ', Predicates.any());
        for (char decor : new char[] { 'x', 'o', 'q' }) builder = builder.where(decor, Predicates.any());
        return builder.build();
    }
